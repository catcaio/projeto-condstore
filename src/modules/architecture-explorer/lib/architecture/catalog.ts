function buildNodes(defs: typeof D): ArchNode[] {
  return defs.map((d) => ({
    id: d.id,
    name: d.name,
    kind: d.kind,
    domain: d.domain,
    status: d.status,
    path: d.path,
    description: d.desc,
    responsibilities: d.does ?? [],
    dependencies: d.deps ?? [],
    relatedFiles: d.files ?? [],
    github: d.path ? githubUrl(d.path) : undefined,
    evidence: d.evidence,
    technologies: d.tech ?? [],
    mvp: d.mvp,
    tags: d.tags ?? [],
    parentId: d.parent,
    layer: d.layer,
  }));
}

