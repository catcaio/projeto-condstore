export function childrenOf(id: string): ArchNode[] {
  return NODES.filter((n) => n.parentId === id);
}

export function dependentsOf(id: string): string[] {
  return EDGES.filter((e) => e.target === id || (e.source === id && e.type === "depends")).map((e) =>
    e.target === id ? e.source : e.target,
  );
}
